const norm = s => s.toLowerCase().replace(/[^a-z0-9]/g, '');
const out = {};
for (const [name, file] of Object.entries(ICONS)) {
  let src = fs.readFileSync(path.join(dir, `${file}.js`), 'utf8');
  const re = /export \{ default \} from '\.\/([\w-]+)\.js'/.exec(src);
  if (re) {
    src = fs.readFileSync(path.join(dir, `${re[1]}.js`), 'utf8');
  }
  const m = /const __iconNode = (\[[\s\S]*?\]);\n/.exec(src);
  if (!m) {
    throw new Error(`no node in ${file}`);
  }
  // eslint-disable-next-line no-new-func
  const node = new Function(`return ${m[1]}`)();
  out[name] = node.map(([tag, attrs]) => {
    const { key: _k, ...rest } = attrs;
    return [tag, rest];
  });
}
const aliases = {};
for (const [alias, target] of Object.entries(ALIASES)) {
  if (!out[target]) {
    throw new Error(`alias ${alias} -> missing ${target}`);
  }
  const k = norm(alias);
  if (Object.keys(out).some(n => norm(n) === k)) {
    continue;
  } // a real name wins
  aliases[k] = target;
}
// lucide's own kebab names resolve too ("circle-check" -> CheckCircle).
for (const [name, file] of Object.entries(ICONS)) {
  const k = norm(file);
  if (!Object.keys(out).some(n => norm(n) === k) && !aliases[k]) {
    aliases[k] = name;
  }
}

const lines = [
  '/**',
  ` * Icon path data for \`<x-icon>\` — GENERATED from lucide-react ${version} (ISC licence,`,
  ' * https://lucide.dev), so a deck renders without loading any icon runtime.',
  ' * Regenerate rather than hand-edit; the names and aliases are listed in the',
  ' * generator: `packages/core/scripts/generate-deck-icons.mjs`.',
  ' */',
  '',
  '/* eslint-disable style/max-len */',
  '',
  'export type IconNode = ReadonlyArray<readonly [string, Readonly<Record<string, string>>]>;',
  '',
  `export const LUCIDE_VERSION = '${version}';`,
  '',
  'export const ICON_NODES: Readonly<Record<string, IconNode>> = {',
  ...Object.entries(out).map(([n, node]) => `  ${n}: ${JSON.stringify(node).replace(/"([a-z][\w-]*)":/gi, (m0, k) => (/^[a-z]\w*$/i.test(k) ? `${k}:` : `'${k}':`)).replace(/"/g, '\'')},`),
  '};',
  '',
  '/** Normalised alias (lowercase, letters and digits) → icon name. */',
  'export const ICON_ALIASES: Readonly<Record<string, string>> = {',
  ...Object.entries(aliases).sort(([a], [b]) => a.localeCompare(b)).map(([k, v]) => `  ${/^[a-z]\w*$/.test(k) ? k : `'${k}'`}: '${v}',`),
  '};',
  '',
];
fs.writeFileSync(path.join(root, 'packages/core/src/libs/decks/iconData.ts'), lines.join('\n'));
